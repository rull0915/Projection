//====================================================//
// クラス宣言
//====================================================//
class TimeSettings
{
private:
	//-----------------------------------------------------
	// メンバ変数
	//-----------------------------------------------------

	// 時間のスケール
	float m_timeScale;

private:

	//-----------------------------------------------------
	// コンストラクタ / デストラクタ
	//-----------------------------------------------------
	TimeSettings()
		: m_timeScale{ 1.0f }
	{};
	~TimeSettings() = default;

public:
	//-----------------------------------------------------
	// 公開関数
	//-----------------------------------------------------

	// シングルトン化
	static TimeSettings& Instance()
	{
		static TimeSettings instance;
		return instance;
	}

	//-----------------------------------------------------
	// ゲッター
	//-----------------------------------------------------
	float GetTimeScale() const { return m_timeScale; }

	//-----------------------------------------------------
	// セッター
	//-----------------------------------------------------
	void SetTimeScale(float scale) { m_timeScale = scale; }
};