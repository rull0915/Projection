#pragma once

#define IS_COMPONENT(Dialog)

//====================================================//
// インクルードファイル
//====================================================//
#include "Components/UI/UIComponentBase.h"

//====================================================//
// 前方宣言
//====================================================//


//====================================================//
// クラス宣言
//====================================================//
class Dialog : public REngine::UIComponentBase
{
private:

	//-----------------------------------------------------
	// メンバ変数
	//-----------------------------------------------------
	 
	// 開いているかどうか
	bool m_isOpen;

public:

	//-----------------------------------------------------
	// コンストラクタ / デストラクタ
	//-----------------------------------------------------
	Dialog(REngine::IComponentOwner* own);
	~Dialog() = default;

	//-----------------------------------------------------
	// Type
	//-----------------------------------------------------
	
	COMPONENT_TYPE(Dialog, REngine::UIComponentBase);

	//-----------------------------------------------------
	// 公開関数
	//-----------------------------------------------------

	// 開く関数
	virtual void Show() {};

	// 隠す関数
	virtual void Hide() {};

	// 開閉チェック
	bool IsOpen() const
	{
		return m_isOpen;
	}

protected:

	// 開閉フラグ変更
	void SetOpen(bool open)
	{
		m_isOpen = open;
	}
};
