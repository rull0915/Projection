#include "../UIGraphic.h"

//====================================================//
// 前方宣言
//====================================================//


//====================================================//
// クラス宣言
//====================================================//
class ImageUI : public UIGraphic<ImageUI, UIComponentID::Image>
{
private:

    //-----------------------------------------------------
    // 定数
    //-----------------------------------------------------


    //-----------------------------------------------------
    // メンバ変数
    //-----------------------------------------------------

    // テクスチャ
	ID3D11ShaderResourceView* m_pTexture;

    // Rayと衝突するかどうか
    bool m_raycastTarget;

public:

    //-----------------------------------------------------
    // コンストラクタ / デストラクタ
    //-----------------------------------------------------
    ImageUI(UIObject* pUIObject)
        : UIGraphic(pUIObject)
		, m_pTexture{ nullptr }
        , m_raycastTarget{ true }
	{
    }
    
    ~ImageUI() = default;

    //-----------------------------------------------------
    // 公開関数
    //-----------------------------------------------------

    void Draw(Renderer& renderer) override;

    //-----------------------------------------------------
    // ゲッター
    //-----------------------------------------------------
    bool IsRaycastTarget() const { return m_raycastTarget; }

    //-----------------------------------------------------
    // セッター
    //-----------------------------------------------------

	void SetTexture(ID3D11ShaderResourceView* texture) { m_pTexture = texture; }
    void SetRaycastTarget(bool f) { m_raycastTarget = f; }

private:

    //-----------------------------------------------------
    // 内部実装
    //-----------------------------------------------------

};